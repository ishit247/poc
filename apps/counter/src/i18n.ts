// Interface language (English / Hindi). The English text IS the key: `t('Sell')` returns 'Sell' in English and the
// Hindi entry below in Hindi. A string with no Hindi entry shows in English, so a missing translation never breaks a
// screen. Variables are written {name}. Kept per tablet in localStorage, like text size and theme (prefs.ts).
// Receipts and slips are rendered by @pos/shared and stay English (PLAN.md Q6: thermal printers cannot print Devanagari).
import { useSyncExternalStore } from 'react';

export type Lang = 'en' | 'hi';
export const LANGS: readonly { code: Lang; label: string }[] = [{ code: 'en', label: 'English' }, { code: 'hi', label: 'हिन्दी' }];

const read = (): Lang => {
  try { return localStorage.getItem('pos.lang') === 'hi' ? 'hi' : 'en'; } catch { return 'en'; }
};
let current: Lang = read();
const listeners = new Set<() => void>();

export const getLang = (): Lang => current;
export function setLang(l: Lang): void {
  current = l;
  try { localStorage.setItem('pos.lang', l); } catch { /* keep it for this session only */ }
  document.documentElement.lang = l;
  listeners.forEach((f) => f());
}
/** Call once before the first render. */
export function applyLang(): void { document.documentElement.lang = current; }

