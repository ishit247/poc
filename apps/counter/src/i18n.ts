/** Translate `en` (and fill {vars}). Safe to call outside React; components should use `useT()` so they re-render on a language change. */
export function t(en: string, vars?: Record<string, string | number>): string {
  let s = (current === 'hi' ? HI[en] : undefined) ?? en;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Pick the singular or plural English text by count (Hindi usually needs one form for both; give both keys the same Hindi). {n} is filled in. */
export function tn(n: number, one: string, many: string, vars?: Record<string, string | number>): string {
  return t(n === 1 ? one : many, { n, ...vars });
}

/** Subscribes the component to the language, and returns `t`. */
export function useT(): typeof t {
  useSyncExternalStore((f) => { listeners.add(f); return () => { listeners.delete(f); }; }, getLang);
  return t;
}
export function useLang(): Lang {
  return useSyncExternalStore((f) => { listeners.add(f); return () => { listeners.delete(f); }; }, getLang);
}
